package org.evosuite.eclipse.classpath;

import org.eclipse.core.runtime.CoreException;
import org.eclipse.jdt.core.IClasspathEntry;
import org.eclipse.jdt.core.JavaCore;
import org.eclipse.jdt.ui.wizards.IClasspathContainerPage;
import org.eclipse.jface.wizard.WizardPage;
import org.eclipse.swt.SWT;
import org.eclipse.swt.layout.GridData;
import org.eclipse.swt.layout.GridLayout;
import org.eclipse.swt.widgets.Composite;
import org.eclipse.swt.widgets.Label;
import org.evosuite.eclipse.EvoSuiteJars;

/** The page behind Build Path > Add Library... > EvoSuite Runtime. */
public class EvoSuiteClasspathContainerPage extends WizardPage implements IClasspathContainerPage {

    private IClasspathEntry entry;

    public EvoSuiteClasspathContainerPage() {
        super("evosuiteRuntime");
        setTitle("EvoSuite Runtime");
        setDescription("The library that tests generated by EvoSuite need to compile and run.");
    }

    @Override
    public void createControl(Composite parent) {
        Composite composite = new Composite(parent, SWT.NONE);
        composite.setLayout(new GridLayout(1, false));
        Label label = new Label(composite, SWT.WRAP);
        label.setLayoutData(new GridData(SWT.FILL, SWT.TOP, true, false));
        String location;
        try {
            location = EvoSuiteJars.runtime().getAbsolutePath();
        } catch (CoreException e) {
            location = e.getStatus().getMessage();
            setErrorMessage(location);
        }
        label.setText("Adds the EvoSuite standalone runtime bundled with this plug-in:\n" + location
                + "\n\nMaven and Gradle projects should declare org.evosuite:evosuite-standalone-runtime "
                + "as a test dependency instead, so that command-line builds see it too.");
        setControl(composite);
    }

    @Override
    public boolean finish() {
        if (entry == null) {
            entry = JavaCore.newContainerEntry(EvoSuiteClasspathContainer.PATH);
        }
        return true;
    }

    @Override
    public IClasspathEntry getSelection() {
        return entry;
    }

    @Override
    public void setSelection(IClasspathEntry containerEntry) {
        entry = containerEntry;
    }
}
