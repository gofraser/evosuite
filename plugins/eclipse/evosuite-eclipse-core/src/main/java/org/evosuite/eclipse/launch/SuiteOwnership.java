package org.evosuite.eclipse.launch;

import java.io.IOException;
import java.util.UUID;

import org.eclipse.core.resources.IFile;
import org.eclipse.core.resources.IFolder;
import org.eclipse.core.runtime.CoreException;
import org.eclipse.core.runtime.IPath;
import org.eclipse.core.runtime.QualifiedName;
import org.evosuite.eclipse.Activator;
import org.evosuite.ide.SuiteMerger;

public final class SuiteOwnership {
    private static final String HEADER = "// EvoSuite generated suite: ";
    private static final QualifiedName TOKEN = new QualifiedName(Activator.PLUGIN_ID, "generatedSuite");

    private SuiteOwnership() {}

    public static IFile suite(IFolder folder, String className, String suffix) {
        return folder.getFile(IPath.fromPortableString(className.replace('.', '/') + suffix + ".java"));
    }

    public static boolean generated(IFile file) throws CoreException {
        String source = contents(file);
        return SuiteMerger.isGeneratedSuite(source, name(file)) || owns(file, source);
    }

    static boolean owns(IFile file, String source) throws CoreException {
        String token = file.getPersistentProperty(TOKEN);
        return token != null && marker(source).equals(token) && SuiteMerger.isValidSuite(source, name(file));
    }

    static boolean generatedScaffolding(IFile file, String source) {
        String header = source.stripLeading();
        int end = header.indexOf("*/");
        return header.startsWith("/**") && end > 0
                && header.substring(0, end).contains("tests automatically generated by EvoSuite")
                && SuiteMerger.isValidSuite(source, name(file));
    }

    static String decorate(IFile file, String source) {
        if (!SuiteMerger.isValidSuite(source, name(file))) return source;
        return HEADER + UUID.randomUUID() + System.lineSeparator()
                + (source.startsWith("\uFEFF") ? source.substring(1) : source);
    }

    public static boolean remember(IFile file, String offered) throws CoreException {
        String token = marker(offered);
        if (token.isEmpty() || !ownsMarker(file, token)) return false;
        file.setPersistentProperty(TOKEN, token);
        return true;
    }

    private static boolean ownsMarker(IFile file, String token) throws CoreException {
        String source = contents(file);
        return marker(source).equals(token) && SuiteMerger.isValidSuite(source, name(file));
    }

    private static String marker(String source) {
        if (!source.startsWith(HEADER)) return "";
        String token = source.lines().findFirst().orElse("").substring(HEADER.length());
        try {
            return UUID.fromString(token).toString().equals(token) ? token : "";
        } catch (IllegalArgumentException e) {
            return "";
        }
    }

    static String contents(IFile file) throws CoreException {
        try (var in = file.getContents()) {
            return new String(in.readAllBytes(), file.getCharset());
        } catch (IOException e) {
            throw new CoreException(Activator.error("Cannot read " + file.getFullPath(), e));
        }
    }

    private static String name(IFile file) {
        return file.getName().substring(0, file.getName().length() - ".java".length());
    }
}
