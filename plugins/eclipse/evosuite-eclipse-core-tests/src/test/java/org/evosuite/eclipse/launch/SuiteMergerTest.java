    /** A suite of the same class that resets two classes and initialises two more. */
    private static final String RESETS_CLASSES = """
            /*
             * This file was automatically generated by EvoSuite
             * Generation timestamp omitted for deterministic output
             */

            package demo;

            import demo.Calc;
            import java.sql.Date;
            import java.util.List;
            import java.util.Map;
            import org.evosuite.runtime.EvoRunner;
            import org.evosuite.runtime.EvoRunnerParameters;
            import org.evosuite.runtime.annotation.EvoSuiteClassExclude;
            import org.evosuite.runtime.sandbox.Sandbox.SandboxMode;
            import org.evosuite.runtime.sandbox.Sandbox;
            import org.junit.After;
            import org.junit.AfterClass;
            import org.junit.Before;
            import org.junit.BeforeClass;
            import org.junit.Test;
            import org.junit.runner.RunWith;

            import static org.evosuite.runtime.EvoAssertions.*;
            import static org.junit.Assert.*;

            @RunWith(EvoRunner.class) @EvoRunnerParameters(mockJVMNonDeterminism = true, useVFS = true, useVNET = true, resetStaticState = true, mockGUI = true, timeout = 3000, maxNumberOfThreads = 100, maxNumberOfIterationsPerLoop = 10000, ignoreThreads = {"Image Fetcher"})\s
            public class Calc_ESTest {


              private static void initializeClasses() {
                org.evosuite.runtime.classhandling.ClassStateSupport.initializeClasses(Calc_ESTest.class.getClassLoader() ,
                  "demo.Calc$Box", "demo.Other",
                  "demo.Calc",
                  "demo.Third"
                );
              }\s

              private static void resetClasses() {
                org.evosuite.runtime.classhandling.ClassResetter.getInstance().setClassLoader(Calc_ESTest.class.getClassLoader());\s

                org.evosuite.runtime.classhandling.ClassStateSupport.resetClasses(
                  "demo.Calc",
                  "demo.Calc$Box"
                );
              }

              @Test(timeout = 3000)
              public void test00()  throws Throwable  {
                  Calc calc0 = new Calc();
                  Date date0 = calc0.d((-1L));
                  assertNotNull(date0);
              }

            }
            """;

    @Test
    public void fillsInTheClassListsThatTheExistingSuiteLeftEmpty() {
        SuiteMerger.Result result = SuiteMerger.merge(NOTHING_TO_RESET, RESETS_CLASSES, "Calc_ESTest");

        assertNull(result.incompatibility);
        assertEquals(1, result.added.size());
        assertEquals(method(RESETS_CLASSES, "resetClasses"), method(result.source, "resetClasses"));
        String initialize = method(result.source, "initializeClasses");
        for (String name : List.of("demo.Calc", "demo.Calc$Box", "demo.Other", "demo.Third")) {
            assertEquals(1, count(initialize, '"' + name + '"'), initialize);
        }
    }

    @Test
    public void refusesSuitesWithClassListsItCannotExtend() {
        String existing = NOTHING_TO_RESET.replace("private static void resetClasses() {\n",
                "private static void resetClasses() {\n    // reset by hand\n    demo.Calc.reset();\n");

        assertEquals("it has no resetClasses() to add the new suite's classes to",
                SuiteMerger.merge(existing, RESETS_CLASSES, "Calc_ESTest").incompatibility);
    }

    /** The declaration of the method {@code name} in {@code source}. */
    private static String method(String source, String name) {
        int start = source.indexOf("private static void " + name + "()");
        return source.substring(start, source.indexOf("\n  }", start) + 4);
    }

    private static String junit4Suite(List<String> classes, String... tests) {
        String names = "\"" + String.join("\",\n      \"", classes) + "\"";
        return "package demo;\n\n"
                + "import org.evosuite.runtime.EvoRunner;\n"
                + "import org.evosuite.runtime.EvoRunnerParameters;\n"
                + "import org.junit.Test;\n"
                + "import org.junit.runner.RunWith;\n\n"
                + "import static org.junit.Assert.*;\n\n"
                + "@RunWith(EvoRunner.class) " + RUNNER_PARAMETERS + "\n"
                + "public class Calculator_ESTest {\n"
                + "  private static void initializeClasses() {\n"
                + "    org.evosuite.runtime.classhandling.ClassStateSupport.initializeClasses("
                + "Calculator_ESTest.class.getClassLoader() ,\n      " + names + "\n    );\n  }\n"
                + "  private static void resetClasses() {\n"
                + "    org.evosuite.runtime.classhandling.ClassStateSupport.resetClasses(\n      " + names
                + "\n    );\n  }\n"
                + String.join("", tests)
                + "}\n";
    }

    @Test
    public void mergesIntoAWorkspaceFileAndKeepsTheOldContentInTheHistory() throws Exception {
        IJavaProject project = TestProjects.create("merge", "src", null);
        IFile file = TestProjects.addSource(project, "src", "demo.Calculator_ESTest", suite("", MAX));

        SuiteMerger.Result result = SuiteMerger.mergeInto(file, suite("", SIGN), "Calculator_ESTest", null);

        assertEquals(List.of("test1"), result.added);
        assertEquals(suite("", MAX, SIGN), read(file));
        assertEquals(1, file.getHistory(null).length, "the previous content is not in the local history");
    }

    @Test
    public void leavesFilesWithUnsavedChangesAlone() throws Exception {
        IJavaProject project = TestProjects.create("merge-dirty", "src", null);
        IFile file = TestProjects.addSource(project, "src", "demo.Calculator_ESTest", suite("", MAX));
        ITextFileBufferManager manager = FileBuffers.getTextFileBufferManager();
        manager.connect(file.getFullPath(), LocationKind.IFILE, null);
        try {
            manager.getTextFileBuffer(file.getFullPath(), LocationKind.IFILE).getDocument().replace(0, 0, "// edited\n");

            SuiteMerger.Result result = SuiteMerger.mergeInto(file, suite("", SIGN), "Calculator_ESTest", null);

            assertEquals("Calculator_ESTest.java has unsaved changes in an editor", result.incompatibility);
            assertEquals(suite("", MAX), read(file));
        } finally {
            manager.disconnect(file.getFullPath(), LocationKind.IFILE, null);
        }
    }

    @Test
    public void keepsTheByteOrderMarkOfTheExistingSuite() throws Exception {
        IJavaProject project = TestProjects.create("merge-bom", "src", null);
        IFile file = TestProjects.addSource(project, "src", "demo.Calculator_ESTest", "\uFEFF" + suite("", MAX));
        file.setCharset("UTF-8", null);

        SuiteMerger.Result result = SuiteMerger.mergeInto(file, suite("", SIGN), "Calculator_ESTest", null);

        assertNull(result.incompatibility);
        assertEquals(List.of("test1"), result.added);
        assertEquals("\uFEFF" + suite("", MAX, SIGN), read(file));
        assertEquals(1, SuiteMerger.testCount("\uFEFF" + suite("", MAX), "Calculator_ESTest"));
    }

    private static String read(IFile file) throws Exception {
        try (var in = file.getContents()) {
            return new String(in.readAllBytes(), StandardCharsets.UTF_8);
        }
    }

    private static int count(String text, String part) {
        int count = 0;
        for (int i = text.indexOf(part); i >= 0; i = text.indexOf(part, i + 1)) {
            count++;
        }
        return count;
    }

