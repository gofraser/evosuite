package org.evosuite.eclipse.ui;

import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.Charset;
import java.util.ArrayList;
import java.util.List;

import org.eclipse.compare.CompareConfiguration;
import org.eclipse.compare.CompareEditorInput;
import org.eclipse.compare.CompareUI;
import org.eclipse.compare.IEditableContent;
import org.eclipse.compare.IEncodedStreamContentAccessor;
import org.eclipse.compare.ITypedElement;
import org.eclipse.compare.structuremergeviewer.DiffNode;
import org.eclipse.compare.structuremergeviewer.Differencer;
import org.eclipse.core.resources.IFile;
import org.eclipse.core.resources.IResource;
import org.eclipse.core.runtime.CoreException;
import org.eclipse.core.runtime.IProgressMonitor;
import org.eclipse.swt.graphics.Image;
import org.evosuite.eclipse.Activator;

/**
 * Shows existing test suites next to the suites EvoSuite has just generated for the same
 * classes: the existing file on the left, editable, the new suite on the right, read-only. The
 * user copies over what they want; saving writes the workspace files, which keep their previous
 * contents in the local history. One suite shows directly, several as a list to pick from, so
 * that a run over many classes opens one editor rather than one per class.
 */
public class SuiteComparison extends CompareEditorInput {

    /** An existing suite and the source of the new one. */
    public record Pair(IFile existing, String generatedSource) {
    }

    private final List<Pair> pairs;
    private final List<WorkspaceSide> sides = new ArrayList<>();

    public SuiteComparison(List<Pair> pairs) {
        super(configuration());
        this.pairs = List.copyOf(pairs);
        setTitle(pairs.size() == 1 ? "EvoSuite: " + pairs.get(0).existing().getName()
                : "EvoSuite: " + pairs.size() + " test suites");
    }

    private static CompareConfiguration configuration() {
        CompareConfiguration configuration = new CompareConfiguration();
        configuration.setLeftEditable(true);
        configuration.setRightEditable(false);
        configuration.setLeftLabel("Existing suite (saving updates it)");
        configuration.setRightLabel("Generated by EvoSuite");
        return configuration;
    }

    /** Opens the comparison in an editor; call in the UI thread. */
    public static void open(List<Pair> pairs) {
        CompareUI.openCompareEditor(new SuiteComparison(pairs));
    }

    @Override
    protected Object prepareInput(IProgressMonitor monitor) {
        sides.clear();
        if (pairs.size() == 1) {
            return node(null, pairs.get(0));
        }
        DiffNode root = new DiffNode(Differencer.NO_CHANGE);
        for (Pair pair : pairs) {
            node(root, pair);
        }
        return root;
    }

    private DiffNode node(DiffNode parent, Pair pair) {
        WorkspaceSide left = new WorkspaceSide(pair.existing());
        sides.add(left);
        GeneratedSide right = new GeneratedSide(pair.existing().getName(), pair.generatedSource(),
                left.getCharset());
        return new DiffNode(parent, Differencer.CHANGE, null, left, right);
    }

    @Override
    public void saveChanges(IProgressMonitor monitor) throws CoreException {
        // Moves what the viewers show into the sides.
        super.saveChanges(monitor);
        for (WorkspaceSide side : sides) {
            side.commit(monitor);
        }
    }

    /** The existing suites, in the order the comparison lists them. */
    public List<IFile> getExistingSuites() {
        return pairs.stream().map(Pair::existing).toList();
    }

    /** The workspace file: editable, written on save. */
    static final class WorkspaceSide implements ITypedElement, IEncodedStreamContentAccessor, IEditableContent {
        private final IFile file;
        private byte[] content;
        private boolean changed;

        WorkspaceSide(IFile file) {
            this.file = file;
        }

        @Override
        public String getName() {
            return file.getName();
        }

        @Override
        public Image getImage() {
            return CompareUI.getImage(file);
        }

        @Override
        public String getType() {
            return file.getFileExtension();
        }

        @Override
        public InputStream getContents() throws CoreException {
            if (content == null) {
                try (InputStream in = file.getContents(true)) {
                    content = in.readAllBytes();
                } catch (IOException e) {
                    throw new CoreException(Activator.error("Cannot read " + file.getFullPath(), e));
                }
            }
            return new ByteArrayInputStream(content);
        }

        @Override
        public String getCharset() {
            try {
                return file.getCharset();
            } catch (CoreException e) {
                return null;
            }
        }

        @Override
        public boolean isEditable() {
            return true;
        }

        @Override
        public ITypedElement replace(ITypedElement dest, ITypedElement src) {
            return dest;
        }

        @Override
        public void setContent(byte[] newContent) {
            content = newContent;
            changed = true;
        }

        void commit(IProgressMonitor monitor) throws CoreException {
            if (changed) {
                file.setContents(new ByteArrayInputStream(content), IResource.KEEP_HISTORY, monitor);
                changed = false;
            }
        }
    }

    /** The new suite, held in memory: its temporary file is gone by the time the editor opens. */
    static final class GeneratedSide implements ITypedElement, IEncodedStreamContentAccessor {
        private final String name;
        private final String source;
        private final String charset;

        GeneratedSide(String name, String source, String charset) {
            this.name = name;
            this.source = source;
            this.charset = charset == null ? Charset.defaultCharset().name() : charset;
        }

        @Override
        public String getName() {
            return name;
        }

        @Override
        public Image getImage() {
            return null;
        }

        @Override
        public String getType() {
            return "java";
        }

        @Override
        public InputStream getContents() {
            return new ByteArrayInputStream(source.getBytes(Charset.forName(charset)));
        }

        @Override
        public String getCharset() {
            return charset;
        }
    }
}
