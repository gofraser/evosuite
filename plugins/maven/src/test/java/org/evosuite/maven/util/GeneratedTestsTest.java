package org.evosuite.maven.util;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Arrays;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

public class GeneratedTestsTest {

    @TempDir
    Path tmp;

    @Test
    public void extensionModeTestNeedsRuntimeAndJupiter() throws IOException {
        Path folder = tmp.resolve("tests");
        write(folder.resolve("com/example/Foo_ESTest.java"),
                "/*\n * This file was automatically generated by EvoSuite\n */",
                "package com.example;",
                "import org.junit.jupiter.api.Test;",
                "import static org.junit.jupiter.api.Assertions.*;",
                "import org.evosuite.runtime.EvoSuiteExtension;",
                "public class Foo_ESTest {",
                "  // import org.junit.Test; in a comment after the imports does not count",
                "}");

        GeneratedTests.Requirements needed = GeneratedTests.scanRequirements(folder.toFile());

        assertTrue(needed.evosuiteRuntime);
        assertTrue(needed.jupiter);
        assertFalse(needed.junit4);
    }

    @Test
    public void legacyTestNeedsJUnit4() throws IOException {
        Path folder = tmp.resolve("tests");
        write(folder.resolve("Foo_ESTest.java"),
                "import org.junit.Test;",
                "import static org.junit.Assert.*;",
                "import org.evosuite.runtime.EvoRunner;",
                "import org.junit.runner.RunWith;",
                "@RunWith(EvoRunner.class)",
                "public class Foo_ESTest extends Foo_ESTest_scaffolding {}");

        GeneratedTests.Requirements needed = GeneratedTests.scanRequirements(folder.toFile());

        assertTrue(needed.evosuiteRuntime);
        assertTrue(needed.junit4);
        assertFalse(needed.jupiter);
    }

    @Test
    public void missingFolderNeedsNothing() throws IOException {
        GeneratedTests.Requirements needed = GeneratedTests.scanRequirements(tmp.resolve("absent").toFile());
        assertFalse(needed.evosuiteRuntime || needed.jupiter || needed.junit4);
    }

    @Test
    public void agentIsAppendedOnceAfterOtherAgents() {
        File jar = new File("/repo/evosuite-standalone-runtime.jar");
        String jacoco = "-javaagent:/repo/jacoco.jar=destfile=target/jacoco.exec";

        String first = GeneratedTests.appendAgent(jacoco, jar);
        assertEquals(jacoco + " -javaagent:" + jar.getAbsolutePath(), first);
        assertEquals(first, GeneratedTests.appendAgent(first, jar), "running setup twice added the agent twice");
        assertEquals("-javaagent:" + jar.getAbsolutePath(), GeneratedTests.appendAgent(null, jar));
    }

    @Test
    public void agentPathWithSpacesIsQuoted() {
        File jar = new File("/my repo/runtime.jar");
        assertEquals("\"-javaagent:" + jar.getAbsolutePath() + "\"", GeneratedTests.appendAgent("", jar));
    }

    private static final String[] HEADER = {
        "/*", " * This file was automatically generated by EvoSuite", " */", "package com.example;"};

    @Test
    public void testsForRemovedClassesAreStale() throws IOException {
        Path folder = tmp.resolve("tests");
        Path classes = tmp.resolve("classes");
        write(classes.resolve("com/example/Kept.class"), "");
        Path kept = write(folder.resolve("com/example/Kept_ESTest.java"), HEADER);
        Path gone = write(folder.resolve("com/example/Gone_ESTest.java"), HEADER);
        Path goneScaffolding = write(folder.resolve("com/example/Gone_ESTest_scaffolding.java"),
                "/**", " * Scaffolding file used to store all the setups needed to run ",
                " * tests automatically generated by EvoSuite", " */");
        Path handWritten = write(folder.resolve("com/example/GoneTest.java"), HEADER);

        List<Path> stale = GeneratedTests.findStaleTests(folder.toFile(), classes.toFile(), "_ESTest");

        assertEquals(Arrays.asList(gone, goneScaffolding), stale);
        assertFalse(stale.contains(kept));
        assertFalse(stale.contains(handWritten));
    }

    @Test
    public void handWrittenTestWithTheSuffixIsNotStale() throws IOException {
        Path folder = tmp.resolve("tests");
        Path classes = tmp.resolve("classes");
        write(classes.resolve("com/example/Kept.class"), "");
        write(folder.resolve("com/example/Gone_ESTest.java"),
                "package com.example;", "public class Gone_ESTest {}");
        write(folder.resolve("com/example/Gone_ESTest_scaffolding.java"),
                "package com.example;", "public class Gone_ESTest_scaffolding {}");

        assertTrue(GeneratedTests.findStaleTests(folder.toFile(), classes.toFile(), "_ESTest").isEmpty());
    }

    @Test
    public void customSuffixIsHonoured() throws IOException {
        Path folder = tmp.resolve("tests");
        Path classes = tmp.resolve("classes");
        write(classes.resolve("com/example/Kept.class"), "");
        Path gone = write(folder.resolve("com/example/GoneGenerated.java"), HEADER);
        Path goneScaffolding = write(folder.resolve("com/example/GoneGenerated_scaffolding.java"), HEADER);
        write(folder.resolve("com/example/Gone_ESTest.java"), HEADER);

        List<Path> stale = GeneratedTests.findStaleTests(folder.toFile(), classes.toFile(), "Generated");

        assertEquals(Arrays.asList(gone, goneScaffolding), stale);
    }

    @Test
    public void partialCompilationOnlyKeepsTestsOfCompiledClasses() throws IOException {
        Path folder = tmp.resolve("tests");
        Path classes = tmp.resolve("classes");
        write(classes.resolve("com/example/Compiled.class"), "");
        Path compiled = write(folder.resolve("com/example/Compiled_ESTest.java"), HEADER);
        Path missing = write(folder.resolve("com/example/Missing_ESTest.java"), HEADER);

        List<Path> stale = GeneratedTests.findStaleTests(folder.toFile(), classes.toFile(), "_ESTest");

        assertEquals(Arrays.asList(missing), stale);
        assertFalse(stale.contains(compiled));
    }

    @Test
    public void nothingIsStaleWithoutCompiledClasses() throws IOException {
        Path folder = tmp.resolve("tests");
        write(folder.resolve("com/example/Foo_ESTest.java"), HEADER);
        Files.createDirectories(tmp.resolve("classes"));

        assertTrue(GeneratedTests.findStaleTests(folder.toFile(), tmp.resolve("classes").toFile(), "_ESTest")
                .isEmpty());
        assertTrue(GeneratedTests.findStaleTests(folder.toFile(), tmp.resolve("absent").toFile(), "_ESTest")
                .isEmpty());
    }

    private static Path write(Path file, String... lines) throws IOException {
        Files.createDirectories(file.getParent());
        Files.write(file, Arrays.asList(lines), StandardCharsets.UTF_8);
        return file;
    }
}
